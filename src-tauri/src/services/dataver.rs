//! データ形式バージョン（「再構築」の要否判断の単一ソース）。
//!
//! アカウントごとに「どのバージョンでデータを作ったか」を accounts.ingest_version /
//! parse_version に記録し、「再構築」はここの現行値と比べて実行内容を自動で選ぶ:
//! - ingest_version が古い → サーバーから全体再取り込み（完了後にローカル再解析も走る）
//! - それ以外 → ローカル再解析のみ（保存済み本文から作り直し・通信なし）

/// サーバー取り込み形式のバージョン。取り込みパイプラインが保存する内容・形を変えたら
/// +1 する（例: uid の保存開始、添付メタの追加、全期間取り込みへの変更）。
pub const INGEST_VERSION: i64 = 1;

/// ローカル解析のバージョン。引用分離・スレッド束ね・代表フラグなど、保存済み本文から
/// 再計算できる加工ロジックを変えたら +1 する。
/// v2: インライン引用の後ろに書いた新規テキストを clean_body に残すよう split_reply を改良。
/// v3: 連なった「元のメッセージ」を 1 通ずつの引用ブロックに分け、Outlook 等の見出しから
///     差出人・日時を取り、手元のメールと照らし合わせる（matched_email_id）。
/// v4: 太字の跡の付いた見出し（"*From:*" / "*Sent:*"）と、引用の途中の属性行（"On … wrote:" 等）
///     でも 1 通ずつに分ける。字下げした転送の中の 1 通は左に寄せる。
pub const PARSE_VERSION: i64 = 4;

/// 記録された取り込み形式バージョンから、サーバーからの全体再取り込みが必要かを判定する。
/// 0（形式不明＝バージョン記録導入前のアカウント）も「必要」になる。
pub fn needs_resync(ingest_stored: i64) -> bool {
    ingest_stored < INGEST_VERSION
}
