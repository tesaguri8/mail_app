//! データ形式バージョン（「再構築」の要否判断の単一ソース）。
//!
//! アカウントごとに「どのバージョンでデータを作ったか」を accounts.ingest_version /
//! parse_version に記録し、「再構築」はここの現行値と比べて実行内容を自動で選ぶ:
//! - ingest_version が古い → サーバーから全体再取り込み（完了後にローカル再解析も走る）
//! - それ以外 → ローカル再解析のみ（保存済み本文から作り直し・通信なし）

/// サーバー取り込み形式のバージョン。取り込みパイプラインが保存する内容・形を変えたら
/// +1 する（例: uid の保存開始、添付メタの追加、全期間取り込みへの変更）。
pub const INGEST_VERSION: i64 = 1;

/// ローカル解析のバージョン。引用分離・スレッド束ね・代表フラグなど、保存済み本文から
/// 再計算できる加工ロジックを変えたら +1 する。
/// v2: インライン引用の後ろに書いた新規テキストを clean_body に残すよう split_reply を改良。
/// v3: 連なった「元のメッセージ」を 1 通ずつの引用ブロックに分け、Outlook 等の見出しから
///     差出人・日時を取り、手元のメールと照らし合わせる（matched_email_id）。
/// v4: 太字の跡の付いた見出し（"*From:*" / "*Sent:*"）と、引用の途中の属性行（"On … wrote:" 等）
///     でも 1 通ずつに分ける。字下げした転送の中の 1 通は左に寄せる。
/// v5: Thunderbird が HTML の表を文字にした見出し（項目名と値が別の行・間に空行）を読み、
///     その転送も 1 通に分ける。既知の形で読めない見出しも、差出人・日付などの見出しが近くに
///     固まっていれば 1 通の区切りとみなす（予備の判定）。iPhone の「日付、名前 <addr> のメール:」の
///     日時も読む。
/// v6: 属性行から差出人だけを取っていた形（Apple Mail の "Sep 9, 2026, 9:09 AM +0900, 名前 <addr>:" /
///     Gmail 日本語版の "2026年10月2日(金) 17:55 名前 <addr>:" / "… に addr 名前:" / 中国語の "写道"）でも
///     日時を読む。年が後の「10月 2 2026」も日時として読む。
/// v7: 罫線だけの行は、次に見出しが来るときだけ引用の区切りとみなす（メールマガジンの飾りの罫線の
///     後ろを本文に残す）。改行で 2 行に割れた属性行をつないで読む。Android 版 Gmail の
///     "火, 20 10月 2026、11:21 名前:" と、曜日が「(月)」の日時を読む。アドレスも続く見出しも無い
///     「送信者：名前」では切らない。
/// v8: 属性行の差出人の名前にカンマがある形（"On …, Kinjo, Aya <addr> wrote:" /
///     "2026/10/14(水) 12:50 +0900 Kinjo, Aya <addr> さんが書きました:"）を、名前のカンマで割らずに読む。
/// v9: 見出しの各行の間に空行が入る書き方（HTML を文字にしたときの 2 重改行。"差出人:" "日付:" …
///     が 1 行おきに並ぶ）でも、空行の先がまだ読んでいない種類の項目なら見出しとして読み続け、日時まで取る。
/// v10: 診断（quotes::diag）で見つかった形を読む。空行を挟む見出しの途中の知らない項目（"Reply:"）で
///      止まらない／コロンの無い「差出人 \"名前\" <addr>」（区切りの後だけ）／1 行に詰まった
///      "From：…To：…日時：…件名：…"／"On <日時>" と "名前 <addr> wrote:" に割れた属性行／「>」の中の見出し。
///      本文の「Cc：各位」・罫線の後の「送信元：店名」「日時：…」の案内は 1 通の始まりにしない。
/// v11: text/plain の本文に HTML の文字参照（"&nbsp;" / "&amp;" ほか）がそのまま書かれたメールは、
///     解いてから body_plain にする（取り込み・再構築とも。`parser::decode_literal_entities`）。
///     "&nbsp;" が 1 つでもあるか、ほかの文字参照が 3 つ以上あるときだけ解く。
/// v12: 差出人の行が無い「>」だけの引用の差出人を、返信の相手から推定する（message_quotes.guessed_from。
///      quotes::guess / store::quote_guess）。推定した差出人の、このメールより前のメールと本文で照らし合わせる。
/// v13: 推定の向きを直す。相手から届いた返信の「>」は自分が前に送った文なので、推定は自分（宛先に書かれた
///      自分の書き方、無ければ受けたアカウントの表示名とアドレス）。照合は自分の全アカウントから送った前のメールと。
///      v12 は相手を推定していた（誤り）。
pub const PARSE_VERSION: i64 = 13;

/// 記録された取り込み形式バージョンから、サーバーからの全体再取り込みが必要かを判定する。
/// 0（形式不明＝バージョン記録導入前のアカウント）も「必要」になる。
pub fn needs_resync(ingest_stored: i64) -> bool {
    ingest_stored < INGEST_VERSION
}
